#!/usr/bin/env node
/* Generate worker/src/schools.js: the schools Suite's edge API answers CFBD
   questions for - every program in the registry (teams/index.js), by the
   name the app sends, which is ESPN's `location` and the registry's `name`.

   Why a list at all (bug hunt, 2026-10-02): the CFBD route asked CFBD for
   any name it was given, and each new (school, season) costs one call
   against the key's monthly allowance. A script asking for made-up names
   could spend it, and Matchup's yards-allowed rows would go blank for every
   fan. Now a name not on this list never reaches CFBD.

   Run by the registry's own workflow (roster.yml) whenever the registry
   changes, and by the edge API's deploy (worker.yml), so what is deployed is
   never older than the registry it came from.

   Usage:  node tools/build-worker-schools.js [--check]
           --check: exit 1 if the committed file is not what it would write */
"use strict";
var fs = require("fs"), path = require("path"), vm = require("vm");
var root = path.join(__dirname, "..");
var out = path.join(root, "worker", "src", "schools.js");

var c = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root, "teams", "index.js"), "utf8") + "\nthis.R = TEAM_REGISTRY;", c);
var names = c.R.map(function (t) { return t.name; }).filter(Boolean)
  .filter(function (n, i, a) { return a.indexOf(n) === i; }).sort();
if (names.length < 100) { console.error("only " + names.length + " schools in the registry - refusing"); process.exit(1); }

var text = "/* GENERATED by tools/build-worker-schools.js from teams/index.js - do not\n" +
           "   edit. The schools the CFBD route answers for (decision 0030). */\n" +
           "export const SCHOOLS = [\n" +
           names.map(function (n) { return "  " + JSON.stringify(n); }).join(",\n") + "\n];\n";

if (process.argv.indexOf("--check") > -1) {
  var have = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (have !== text) { console.error("worker/src/schools.js is out of step with teams/index.js: run node tools/build-worker-schools.js"); process.exit(1); }
  console.log("worker/src/schools.js matches the registry (" + names.length + " schools)");
} else {
  fs.writeFileSync(out, text);
  console.log("worker/src/schools.js: " + names.length + " schools");
}
