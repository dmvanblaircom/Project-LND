#!/usr/bin/env node
/* Generate worker/src/schools.js: each selectable program's Suite id by its
   provider id, so a game alert opens the team it is about (code review,
   2026-11-09). From the registry (teams/index.js).

   It also listed the schools the CFBD season route answered for; that route
   and the ranks route had no caller after decision 0044 and were removed
   (2026-11-19).

   Run by the registry's own workflow (roster.yml) whenever the registry
   changes, and by the edge API's deploy (worker.yml), so what is deployed is
   never older than the registry it came from.

   Usage:  node tools/build-worker-schools.js [--check]
           --check: exit 1 if the committed file is not what it would write */
"use strict";
var fs = require("fs"), path = require("path"), vm = require("vm");
var root = path.join(__dirname, "..");
var out = path.join(root, "worker", "src", "schools.js");

var c = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root, "teams", "index.js"), "utf8") + "\nthis.R = TEAM_REGISTRY;", c);
if (c.R.length < 100) { console.error("only " + c.R.length + " programs in the registry - refusing"); process.exit(1); }

// Each selectable program's Suite id by its provider id: an alert opens the
// team it is about (code review, 2026-11-09 - one phone can follow several).
var ids = {};
c.R.filter(function (t) { return t.config && t.providerId && t.id; }).forEach(function (t) { ids[t.providerId] = t.id; });
var idKeys = Object.keys(ids).sort(function (a, b) { return +a - +b; });
var text = "/* GENERATED by tools/build-worker-schools.js from teams/index.js - do not\n" +
           "   edit. Each program's Suite id by its provider id, for an alert's link. */\n" +
           "export const SUITE_IDS = {\n" +
           idKeys.map(function (k) { return "  " + JSON.stringify(k) + ": " + JSON.stringify(ids[k]); }).join(",\n") + "\n};\n";

if (process.argv.indexOf("--check") > -1) {
  var have = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (have !== text) { console.error("worker/src/schools.js is out of step with teams/index.js: run node tools/build-worker-schools.js"); process.exit(1); }
  console.log("worker/src/schools.js matches the registry (" + idKeys.length + " programs)");
} else {
  fs.writeFileSync(out, text);
  console.log("worker/src/schools.js: " + idKeys.length + " programs");
}
