#!/usr/bin/env node
/* Generate worker/src/calendar.js: the CFP rankings shows from the league's
   published calendar (leagues/college-football.js, decision 0033), for the
   alerts Worker, which has no browser globals to read it from. The league
   file stays the one place the dates are written; this copies them.

   Usage:  node tools/build-worker-calendar.js [--check]
           --check: exit 1 if the committed file is not what it would write */
"use strict";
var fs = require("fs"), path = require("path"), vm = require("vm");
var root = path.join(__dirname, "..");
var out = path.join(root, "worker", "src", "calendar.js");

var c = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root, "leagues", "college-football.js"), "utf8") + "\nthis.C = LEAGUE_CALENDAR;", c);
var shows = [];
Object.keys(c.C.seasons).sort().forEach(function (season) {
  c.C.seasons[season].forEach(function (e) {
    if (e.kind === "rankings") shows.push({ season: Number(season), n: e.n, start: e.start, end: e.end });
  });
});
var text = "/* GENERATED by tools/build-worker-calendar.js from leagues/college-football.js\n" +
           "   - do not edit. The CFP rankings shows, for the CFP-rankings alert. */\n" +
           "export const RANKINGS_SHOWS = [\n" +
           shows.map(function (s) { return "  " + JSON.stringify(s); }).join(",\n") + "\n];\n";

if (process.argv.indexOf("--check") > -1) {
  var have = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (have !== text) { console.error("worker/src/calendar.js is out of step with leagues/college-football.js: run node tools/build-worker-calendar.js"); process.exit(1); }
  console.log("worker/src/calendar.js matches the league calendar (" + shows.length + " rankings shows)");
} else {
  fs.writeFileSync(out, text);
  console.log("worker/src/calendar.js: " + shows.length + " rankings shows");
}
